"""Write docs/RESULTS.md from out/bench.json so numbers in the docs never drift from the run."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pct(x):
    return f"{round(100 * x)}%"


def main():
    b = json.loads((ROOT / "out" / "bench.json").read_text())
    s, rows = b["samples"]["summary"], b["samples"]["rows"]
    cons = round(sum(r["trailer_min"] + (r["baseline_min"] if r["tier"] == "return" else 0) for r in rows), 1)
    L = ["# Results", "", "Generated by `python3 -m bench.run && python3 -m bench.report`. Do not edit by hand.", "",
         "## Sample agent PRs (hand-planted bugs)", "",
         f"- {s['prs']} PRs: {s['buggy']} with a planted bug, {s['clean']} clean.",
         f"- **Caught:** {s['blocked_with_verified_evidence']} returned to the agent with verified evidence, "
         f"{s['routed_to_human_at_bug']} routed to a human with a question on the faulty file. "
         f"Catch rate {pct(s['catch_rate'])} (strict, verified only: {pct(s['strict_catch_rate'])}).",
         f"- **Escapes:** {s['escaped']}.",
         f"- **False alarms** (a clean PR blocked): {pct(s['false_alarm_rate'])}. Unverified noise on clean PRs: {s['unverified_noise_on_clean']}.",
         f"- **Routing:** light {s['tiers']['light']}, targeted {s['tiers']['targeted']}, full read {s['tiers']['full']}, "
         f"returned to agent {s['tiers']['return']}. Share routed to a human read: {pct(s['share_routed_to_human_read'])}.",
         f"- **Review minutes (modelled):** {s['minutes_baseline']} for line-by-line review of all PRs vs "
         f"{s['minutes_with_trailer']} with trailers ({s['minutes_saved_pct']}% less). "
         "Returned PRs come back after the agent fixes them; that second review is not counted here.",
         f"- **Conservative:** if every returned PR later needs a full line-by-line read, trailers cost "
         f"{cons} minutes ({round(100 * (1 - cons / s['minutes_baseline']), 1)}% less).", "",
         "| PR | Area | Planted bug | Lane | Caught by | Baseline min | Trailer min |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['pr']} | {r['area']} | {r['bug'] or '—'} | {r['tier']} | {', '.join(r['caught_by']) or '—'} | "
                 f"{r['baseline_min']} | {r['trailer_min']} |")
    if "mutants" in b:
        m = b["mutants"]["summary"]
        led = b["mutants"]["ledger"]
        L += ["", "## Mechanical mutants (unbiased check)", "",
              "Each mutant flips one operator, bumps one constant, or deletes one call or raise in the bank code, "
              "and is submitted as a 'tidy-up, no behaviour change' agent PR.", "",
              f"- {m['mutants']} mutants: {m['blocked_with_verified_evidence']} returned with verified evidence "
              f"({pct(m['strict_catch_rate'])}), {m['routed_to_human']} routed to a human, {m['passed_as_light']} passed as a light check.",
              f"- With the per-area trust ledger, escapes that merge on a light check fall from "
              f"{led['escapes_without_ledger']} to {led['escapes_with_ledger']}, at the cost of "
              f"{led['extra_full_reads_from_ledger']} extra full reads.",
              f"- {m['note']}", "", "Survivors:", ""]
        for r in b["mutants"]["rows"]:
            if not r["blocked"]:
                L.append(f"- `{r['mutation']}` → {r['tier']}")
    if "heldout" in b:
        h = b["heldout"]["summary"]
        L += ["", "## Held-out mutants (operator families frozen before running)", "",
              "Dev mutants (operator swaps, constant bumps, deleted calls) were used while fixing the checks. "
              "Held-out mutants use families we never tuned on: string literal changes, and/or swaps, argument swaps, "
              "and a neutralised SQL predicate. Rule: no check may be changed because of a held-out result "
              "without moving that family into dev and adding a new held-out family.", "",
              f"- {h['mutants']} held-out mutants: {h['blocked_with_verified_evidence']} returned with proof "
              f"({pct(h['strict_catch_rate'])}), {h['routed_to_human']} routed to a human, {h['passed_as_light']} passed as light. "
              "Small set: treat it as a smoke test, not a precise rate."]
    if "baselines" in b:
        L += ["", "## Dumb baselines the trailer must beat", "",
              "'Caught' means the PR was blocked on evidence or sent to a human read. 'Full read of everything' assumes "
              "a perfect human reviewer, which flatters it.", ""]
        for setname, rowsb in b["baselines"].items():
            L += [f"**{setname}**", "", "| Router | Catch rate | Clean PRs sent to a human | Minutes |", "|---|---|---|---|"]
            L += [f"| {x['name']} | {pct(x['catch_rate'])} | {x['flags_on_clean']} | {x['minutes']} |" for x in rowsb]
            L.append("")
    if "spot_checks" in b:
        sc = b["spot_checks"]
        L += ["## Human spot checks", "", f"Policy: {sc['policy']}. Of {sc['light_prs']} light-lane PRs, picked "
              f"{', '.join(sc['picked']) or 'none'}; misses found: {', '.join(sc['misses_found']) or 'none'}. "
              "A miss found this way counts as an escape in the trust ledger, so the area loses its light lane."]
    llm_path = ROOT / "out" / "llm_eval.json"
    if llm_path.exists():
        le = json.loads(llm_path.read_text())["summary"]
        labels = json.loads((ROOT / "bench" / "llm_labels.json").read_text())
        claims = [c for k, v in labels.items() if not k.startswith("_") for c in v]
        right = sum(c["correct"] for c in claims)
        L += ["", f"## Optional LLM reviewer ({le['model']}, advisory only)", "",
              f"- {le['raw_findings']} findings on the 13 PRs; {le['dropped_as_ungrounded']} dropped by the quote check "
              f"(hallucination rate {pct(le['hallucination_rate'])}).",
              f"- Pointed at the planted bug's file on {le['buggy_prs_with_grounded_finding_on_bug_file']} buggy PRs, "
              "including PR-109, which the deterministic checks only route as a question.",
              f"- Hand-labelled: {right} of {len(claims)} claims were correct. Wrong ones: "
              + "; ".join(f"{k}: {c['why']}" for k, v in labels.items() if not k.startswith('_') for c in v if not c['correct']) + ".",
              "- Lesson: every wrong claim quoted real code, so grounding filters invented code, not wrong reasoning. "
              "That is why LLM findings route attention and never block."]
    cmp_path = ROOT / "out" / "ai_compare.json"
    if cmp_path.exists():
        c = json.loads(cmp_path.read_text())
        cs = c["summary"]
        L += ["", "## Side by side with AI code reviewers on the same 13 PRs", "",
              f"Each sample PR is a real pull request on GitHub (captured {cs['captured_at']}). "
              f"GitHub Copilot review was {cs['copilot']}.", "",
              f"- **PR Trailer:** {cs['trailer']['caught']}/{cs['trailer']['of']} planted bugs, "
              f"{cs['trailer_reproduced']} of them reproduced and returned to the agent with evidence.",
              f"- **Gemini (our advisory LLM pass):** pointed at {cs['gemini']['caught']}/{cs['gemini']['of']}, as opinion.",
              f"- **Devin Review:** {cs['devin']['caught']}/{cs['devin']['of']} visible on GitHub, plus a 'security issue' "
              f"on the other {cs['devin_hidden_on_bugs']} whose text Devin keeps on its own dashboard.",
              f"- **Codex:** {cs['codex']['caught']}/{cs['codex']['of']}, but it had only reviewed {cs['codex_reviewed']} of the 13 PRs "
              "when captured, and it caught every planted bug in the ones it did review.", "",
              "Our reading: on bugs this size, good AI reviewers find most of them too, so catch rate is not where the trailer wins. "
              "It wins on what the approver gets. A reviewer comment is an opinion to re-check. The trailer reproduces the failure, "
              "returns the PR to the agent without a human, answers \"does it do anything else?\", and puts every clean PR in a lane, "
              "so the approver knows how much to read. Reviewer comments can feed the trailer as advisory items, like Gemini today.", "",
              "| PR | Planted bug | PR Trailer | Gemini | Devin | Codex |", "|---|---|---|---|---|---|"]
        for x in c["rows"]:
            dv, cx = x["devin"], x["codex"]
            fmt = lambda v: ("flagged, text hidden" if v["verdict"] == "hidden" else v["verdict"]) + (f" ({v['hidden']})" if v.get("hidden") else "") + (f": \"{v['quote']}\"" if v.get("quote") else "")
            L.append(f"| {x['pr']} | {x['bug'] or 'none'} | {x['trailer']} | {x['gemini']} | {fmt(dv)} | {fmt(cx)} |")
        L += ["", "Notes: " + " ".join(c["notes"])]
    L += ["", "## Assumptions behind the minutes", "", "```json", json.dumps(b["assumptions"], indent=2), "```",
          "", "Minutes are a model, not a stopwatch. The walkthrough page has a timer so reviewers can replace them with measurements."]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
